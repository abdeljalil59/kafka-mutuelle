-- Un impayé par prélèvement rejeté. id_evenement est l'idEvenement de la cotisation d'origine : sa contrainte d'unicité
-- porte l'idempotence (un résultat rejoué ne crée pas de seconde ligne). Les instants sont des TIMESTAMP WITH TIME ZONE :
-- decide_le est un instant UTC (timestamp-micros du contrat Avro) et ne doit pas dépendre du fuseau de la JVM.
CREATE TABLE IF NOT EXISTS impaye (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_evenement  VARCHAR(36)   NOT NULL,
    id_adherent   VARCHAR(64)   NOT NULL,
    montant       DECIMAL(19,2) NOT NULL,
    decide_le     TIMESTAMP WITH TIME ZONE NOT NULL,
    enregistre_le TIMESTAMP WITH TIME ZONE NOT NULL,
    -- Posé à TRUE, pour tous les impayés d'un adhérent EXISTANT à ce moment, quand sa relance a été publiée. Un impayé
    -- enregistré après la relance naît à FALSE : « une relance a-t-elle été émise pour cet adhérent ? » se lit donc sur
    -- l'ensemble de ses lignes (au moins une à TRUE), pas sur la ligne qui vient d'arriver.
    relance_emise BOOLEAN DEFAULT FALSE NOT NULL,
    CONSTRAINT uq_impaye_id_evenement UNIQUE (id_evenement)
);

-- Le nombre d'impayés par adhérent décide de la relance : un COUNT par adhérent à chaque rejet nouveau.
CREATE INDEX IF NOT EXISTS idx_impaye_id_adherent ON impaye (id_adherent);
